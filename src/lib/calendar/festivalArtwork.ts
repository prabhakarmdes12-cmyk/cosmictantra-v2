/** Normalise any engine tithi shape to an artwork file key. */
export function resolveTithiArtKey(tithi: ArtworkResolvable['tithi']): string | null {
  if (!tithi) return null;
  const name = typeof tithi.name === 'string' ? tithi.name.trim() : '';
  // The month engine stores index 1..30 (see PanchangDayData.tithi.index).
  const rawIndex = tithi.index;
  if (typeof rawIndex === 'number' && rawIndex >= 1 && rawIndex <= 30) {
    const idx = Math.round(rawIndex);
    if (idx === 15) return TITHI_ART.purnima;
    if (idx === 30) return TITHI_ART.amavasya;
    const key = TITHI_NAME_TO_KEY[TITHIS_BY_INDEX[(idx - 1) % 15]];
    if (key) return TITHI_ART[key];
  }
  // Fall back on the English bare name.
  const key = TITHI_NAME_TO_KEY[name];
  if (key) return TITHI_ART[key];
  if (/purnima|पूर्णिमा/i.test(name)) return TITHI_ART.purnima;
  if (/amavasya|अमावस्या/i.test(name)) return TITHI_ART.amavasya;
  return null;
}

const TITHIS_BY_INDEX = [
  'Pratipada', 'Dwitiya', 'Tritiya', 'Chaturthi', 'Panchami',
  'Shashthi', 'Saptami', 'Ashtami', 'Navami', 'Dashami',
  'Ekadashi', 'Dwadashi', 'Trayodashi', 'Chaturdashi', 'Purnima',
];

function asset(key: string): DayArtwork['src'] {
  return `${BASE}/${key}.webp`;
}

function thumb(key: string): DayArtwork['srcThumb'] {
  return `${BASE}/${key}-sm.webp`;
}

function toArtwork(key: string, kind: DayArtwork['kind'], label: string, labelHi: string, isFestivalDay: boolean): DayArtwork {
  return { src: asset(key), srcThumb: thumb(key), kind, key, label, labelHi, isFestivalDay };
}

/**
 * Resolve artwork for one calendar day.
 *
 * Festival days get their dedicated (or category) artwork and
 * `isFestivalDay: true` — the UI renders them with the richer "sticker" cell.
 * Ordinary days always resolve to the symbolic tithi artwork, so no cell is
 * ever blank. Returns null only for truly unrepresentable input (no tithi at
 * all), which callers should treat as "no art".
 */
export function resolveDayArtwork(day: ArtworkResolvable): DayArtwork | null {
  const festivals = Array.isArray(day.festivals) ? day.festivals : [];
  const fname = (f: { name?: unknown }) => (typeof f?.name === 'string' ? f.name : '');
  const fnameHi = (f: { nameHi?: unknown }) => (typeof f?.nameHi === 'string' ? f.nameHi : '');

  // Pass 1 — specific (non-generic) festival artwork. On days that carry both
  // a specific festival and a universal vrat (Diwali on Amavasya, Sharad
  // Purnima on Purnima Vrat, Ganesh Chaturthi on Vinayaka Chaturthi) the
  // SPECIFIC artwork must win regardless of emission order.
  for (const f of festivals) {
    const token = FESTIVAL_TOKENS[fname(f)];
    if (token && !token.generic) {
      return toArtwork(token.art, 'festival', fname(f), fnameHi(f), true);
    }
  }

  // Pass 2 — generic vrat token, else keyword category for unknown names.
  let categoryArt: DayArtwork | null = null;
  for (const f of festivals) {
    const token = FESTIVAL_TOKENS[fname(f)];
    if (token) {
      return toArtwork(token.art, 'festival', fname(f), fnameHi(f), true);
    }
    const cat = categoryByKeyword(fname(f));
    if (cat && !categoryArt) {
      const key = CATEGORY_FALLBACKS[cat];
      categoryArt = toArtwork(key, 'category', fname(f), fnameHi(f), true);
    }
  }
  if (categoryArt) return categoryArt;

  // Pass 3 — symbolic tithi artwork so ordinary days are never blank.
  const tithiKey = resolveTithiArtKey(day.tithi);
  if (tithiKey) {
    const tithiName = typeof day.tithi.name === 'string' ? day.tithi.name : '';
    return toArtwork(
      tithiKey,
      'tithi',
      `Tithi • ${tithiName || ''}`.trim(),
      `${TITHI_LABEL_HI[tithiKey] || ''} तिथि`,
      false
    );
  }
  return null;
}

function categoryByKeyword(name: string): keyof typeof CATEGORY_FALLBACKS | null {
  const n = name.toLowerCase();
  if (n.includes('shiva') || n.includes('शिव')) return 'SHIVA';
  if (n.includes('vishnu') || n.includes('krishna') || n.includes('जन्माष्टमी') || n.includes('विष्णु')) return 'VISHNU_KRISHNA';
  if (n.includes('durga') || n.includes('devi') || n.includes('lakshmi') || n.includes('saraswati') || n.includes('दुर्गा')) return 'DEVI';
  if (n.includes('ganesh') || n.includes('गणेश')) return 'GANESHA';
  if (n.includes('surya') || n.includes('sankranti') || n.includes('छठ') || n.includes('सूर्य')) return 'SURYA';
  if (n.includes('hanuman') || n.includes('ram') || n.includes('राम') || n.includes('हनुमान')) return 'RAM_HANUMAN';
  if (n.includes('purnima') || n.includes('moon') || n.includes('पूर्णिमा')) return 'MOON_PURNIMA';
  if (n.includes('diwali') || n.includes('deep') || n.includes('diyas') || n.includes('दीप')) return 'FESTIVAL_LIGHTS';
  return null;
}

