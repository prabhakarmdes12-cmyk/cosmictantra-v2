/**
 * CosmicTantra calendar festival artwork resolver.
 *
 * Resolves a day's panchang data to an artwork WebP under
 * `/assets/calendar/events/` following the manifest conventions in
 * `docs/EVENT_IMAGE_MANIFEST.json`.
 *
 * Resolution priority per day (first hit wins):
 *   1. a dedicated festival artwork for the first festival on the day;
 *   2. the festival's category fallback artwork (never an empty cell);
 *   3. the day's symbolic tithi artwork (30 tithi×paksha combos → 16 files).
 *
 * Every engine-emitted festival name (English) must be present in
 * `FESTIVAL_TOKENS`. `scripts/verify-artwork-coverage.ts` asserts 100% of the
 * days, festivals and tithi combos emitted by the real engine resolve to a
 * file that exists on disk — a missing token or asset fails the check.
 */

export interface DayArtwork {
  /** Absolute asset path beginning with `/assets/...` (served from /public). */
  src: string;
  /** Lightweight thumb for grid cells (384×216, generated by the build). */
  srcThumb: string;
  /** Human kind of artwork: festival | category | tithi. */
  kind: 'festival' | 'category' | 'tithi';
  /** Machine key (file name without extension) for tests/debug. */
  key: string;
  /** Short label, bilingual where the engine provides it. */
  label: string;
  labelHi: string;
  /** True when a festival-specific artwork was matched (sticker treatment). */
  isFestivalDay: boolean;
}

export interface ArtworkResolvable {
  tithi: { index?: number; name?: string; paksha?: string; [k: string]: unknown };
  festivals?: Array<{ name?: string; nameHi?: string; [k: string]: unknown }>;
  dateString?: string;
}

