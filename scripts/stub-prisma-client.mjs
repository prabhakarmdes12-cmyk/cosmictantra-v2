/**
 * stub-prisma-client.mjs — sandbox toolchain workaround (committed on purpose).
 *
 * In this sandbox `npm install` cannot complete `prisma generate`: the engine
 * binary download (binaries.prisma.sh) is network-blocked. Without the
 * generated client, `@prisma/client` re-exports from `.prisma/client/default`
 * which does not exist, and `tsc --noEmit` fails with:
 *
 *   src/lib/db.ts(1,10): error TS2305: Module '"@prisma/client"' has no
 *   exported member 'PrismaClient'.
 *
 * This script writes a MINIMAL stub into node_modules/.prisma/client so that:
 *   - TypeScript compiles (PrismaClient exists as a type + constructor);
 *   - importing src/lib/db.ts at runtime is safe (construction is lazy);
 *   - actually constructing PrismaClient throws a clear, honest error instead
 *     of a confusing "Cannot find module '.prisma/client/default'".
 *
 * It never touches tracked files; node_modules is not persisted, so run this
 * after every fresh `npm install --ignore-scripts` in the sandbox:
 *
 *   node scripts/stub-prisma-client.mjs
 *
 * Database-backed features are unavailable in the sandbox regardless; nothing
 * in the Kashi V3 / Kundli revamp surface touches Prisma.
 */
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(process.cwd(), 'node_modules', '.prisma', 'client');
mkdirSync(dir, { recursive: true });

const dts = `// Stub generated by scripts/stub-prisma-client.mjs — see file header.
export declare class PrismaClient {
  constructor(options?: { log?: unknown; datasources?: unknown; errorFormat?: unknown });
  $connect(): Promise<void>;
  $disconnect(): Promise<void>;
  $on(event: string, callback: (...args: any[]) => void): void;
  $transaction<T>(arg: any): Promise<T>;
  [model: string]: any;
}
export declare const Prisma: Record<string, any>;
`;

const js = `// Stub generated by scripts/stub-prisma-client.mjs — see file header.
class PrismaClient {
  constructor() {
    throw new Error(
      "@prisma/client stub: 'prisma generate' cannot run in this sandbox " +
      "(engine download blocked). Database-backed features are unavailable; " +
      "all deterministic Kashi/Kundli flows are unaffected."
    );
  }
}
const Prisma = new Proxy({}, { get: () => undefined });
module.exports = { PrismaClient, Prisma };
module.exports.default = module.exports;
`;

const pkg = JSON.stringify(
  { name: '.prisma/client', version: '0.0.0-stub', main: 'default.js', types: 'default.d.ts' },
  null,
  2
);

writeFileSync(join(dir, 'default.d.ts'), dts);
writeFileSync(join(dir, 'default.js'), js);
writeFileSync(join(dir, 'index.d.ts'), dts);
writeFileSync(join(dir, 'index.js'), js);
if (!existsSync(join(dir, 'package.json'))) writeFileSync(join(dir, 'package.json'), pkg);

console.log(`✓ prisma client stub written to ${dir}`);
